-- База данных ООО «Рога и Копыта»
-- Из этого файла собирается shop.db (см. README.md, шаг 2). Сам файл не меняй.

DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS clients;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS categories;

-- Категории товаров
CREATE TABLE categories (
    id   INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

-- Товары. price — цена в рублях, stock — сколько штук лежит на складе
CREATE TABLE products (
    id          INTEGER PRIMARY KEY,
    name        TEXT    NOT NULL,
    category_id INTEGER NOT NULL REFERENCES categories(id),
    price       INTEGER NOT NULL,
    stock       INTEGER NOT NULL
);

-- Клиенты — компании, которые у нас покупают
CREATE TABLE clients (
    id   INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    city TEXT NOT NULL
);

-- Заказы. order_date — дата в формате ГГГГ-ММ-ДД
CREATE TABLE orders (
    id         INTEGER PRIMARY KEY,
    client_id  INTEGER NOT NULL REFERENCES clients(id),
    order_date TEXT    NOT NULL,
    status     TEXT    NOT NULL   -- Новый, Оплачен, Доставлен, Отменён
);

-- Строки заказов: какой товар, сколько штук и по какой цене купили
CREATE TABLE order_items (
    id         INTEGER PRIMARY KEY,
    order_id   INTEGER NOT NULL REFERENCES orders(id),
    product_id INTEGER NOT NULL REFERENCES products(id),
    quantity   INTEGER NOT NULL,
    price      INTEGER NOT NULL
);

